function init(client) {
  client.on('interactionCreate', async (i) => {
    const ok = (i.isChatInputCommand() && i.commandName === '幫助') || (i.isButton() && i.customId === 'adv:help');
    if (!ok) return;
    const embed = new EmbedBuilder().setColor(brandColor())
      .setTitle('🌿 冒險生活 · 指令總表')
      .setDescription('點斜線 `/` 就會跳出指令，直接選即可。')
      .setFooter({ text: '⚠️ 星幣不可私下買賣，只能透過遊戲與管理員兌換' });
    for (const [name, value] of SECTIONS) embed.addFields({ name, value });
    return i.reply({ embeds: [embed], flags: MessageFlags.Ephemeral }).catch(() => {});
  });
  console.log('  ↳ 冒險指令總表 /幫助 已載入');
}

module.exports = { init };
